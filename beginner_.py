def create_study_plan(topic):
    print("\n===== AI STUDY ASSISTANT =====")
    print(f"\nYour Topic: {topic}")

    print("\n1. Study Notes")
    print(f"- Learn the basic concepts of {topic}.")
    print(f"- Understand important terms related to {topic}.")
    print(f"- Practice examples of {topic}.")

    print("\n2. Practice Questions")
    print(f"- What is {topic}?")
    print(f"- Explain the main concepts of {topic}.")
    print(f"- Give one real-world example of {topic}.")

    print("\n3. Study Tips")
    print("- Study for 25 minutes.")
    print("- Practice coding or examples.")
    print("- Review what you learned.")

    print("\n===== END OF STUDY PLAN =====")


print("Welcome to AI Study Assistant!")

while True:
    topic = input("\nEnter a study topic (or 'exit' to quit): ")

    if topic.lower() == "exit":
        print("Thank you for using Study Assistant!")
        break

    if topic.strip() == "":
        print("Please enter a valid topic.")
        continue

    create_study_plan(topic)